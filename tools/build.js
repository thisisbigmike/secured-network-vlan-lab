#!/usr/bin/env node
/*
 * Regenerates the files that are derived from the Packet Tracer configs and topology:
 *   assets/configs.js                    configs embedded for the browser simulator
 *   packet-tracer/addressing-table.csv   IP plan for every device
 *   packet-tracer/cabling-plan.csv       which port connects to which
 * Run after editing anything in packet-tracer/configs/ or assets/topology.js:
 *   node tools/build.js
 */
'use strict';
const fs = require('fs');
const path = require('path');

const root = path.resolve(__dirname, '..');
const cfgDir = path.join(root, 'packet-tracer', 'configs');
const topo = require(path.join(root, 'assets', 'topology.js'));

const configs = {};
for (const f of fs.readdirSync(cfgDir).filter((f) => f.endsWith('.txt')).sort()) {
  configs[path.basename(f, '.txt')] = fs.readFileSync(path.join(cfgDir, f), 'utf8');
}
const js = `/* Generated by tools/build.js from packet-tracer/configs/*.txt - do not edit by hand. */
(function (root) {
  const configs = ${JSON.stringify(configs, null, 2)};
  if (typeof module === 'object' && module.exports) module.exports = configs;
  else root.SECURENET_CONFIGS = configs;
})(typeof self !== 'undefined' ? self : this);
`;
fs.writeFileSync(path.join(root, 'assets', 'configs.js'), js);

const csv = (rows) => rows.map((r) => r.map((c) => (/[",]/.test(String(c)) ? `"${String(c).replace(/"/g, '""')}"` : c)).join(',')).join('\n') + '\n';

const vlanOf = (zone) => (zone && zone.startsWith('v') ? Number(zone.slice(1)) : '');
const zoneName = { v1: 'VLAN 1 Management', v2: 'VLAN 2 Administrative', v3: 'VLAN 3 Maintenance', v4: 'VLAN 4 Account', v5: 'VLAN 5 Works', dmz: 'DMZ', inet: 'Internet' };
const addr = [['Device', 'PT model', 'Zone', 'VLAN', 'Interface', 'IP address', 'Subnet mask', 'Default gateway', 'DNS server']];
addr.push(['R1', 'Cisco 1841', 'Core', '1', 'Fa0/0.1', '192.168.1.1', '255.255.255.0', '', '']);
for (let v = 2; v <= 5; v++) addr.push(['R1', 'Cisco 1841', 'Core', String(v), `Fa0/0.${v}`, `192.168.${v}.1`, '255.255.255.0', '', '']);
addr.push(['R1', 'Cisco 1841', 'Core', '', 'Fa0/1', '172.16.0.1', '255.255.255.252', '', '']);
addr.push(['Switch0', 'Cisco 2960-24TT', 'Core', '1', 'Vlan1 (management)', '192.168.1.2', '255.255.255.0', '192.168.1.1', '']);
addr.push(['ASA1', 'Cisco ASA 5505', 'Inside (100)', '', 'Vlan1 inside - Et0/1', '172.16.0.2', '255.255.255.252', '', '']);
addr.push(['ASA1', 'Cisco ASA 5505', 'Outside (0)', '', 'Vlan2 outside - Et0/0', '209.165.200.226', '255.255.255.248', '209.165.200.225', '']);
addr.push(['ASA1', 'Cisco ASA 5505', 'DMZ (70)', '', 'Vlan3 dmz - Et0/2', '172.16.50.1', '255.255.255.0', '', '']);
addr.push(['ASA1 (static NAT)', '', 'Outside', '', 'public address of DMZ-Server', '209.165.200.227', '', '', '']);
addr.push(['ISP', 'Cisco 1841', 'Internet', '', 'Fa0/0', '209.165.200.225', '255.255.255.248', '', '']);
addr.push(['ISP', 'Cisco 1841', 'Internet', '', 'Fa0/1', '209.165.201.1', '255.255.255.224', '', '']);
for (const [name, d] of Object.entries(topo.devices)) {
  if (!d.ip) continue;
  addr.push([name + (d.optional ? ' (scenario only)' : ''), d.model, zoneName[d.zone] || '', vlanOf(d.zone), 'FastEthernet0', d.ip, d.mask, d.gw || '', d.dns || '']);
}
fs.writeFileSync(path.join(root, 'packet-tracer', 'addressing-table.csv'), csv(addr));

const cableName = { straight: 'Copper Straight-Through', cross: 'Copper Cross-Over' };
const cab = [['From device', 'From port', 'To device', 'To port', 'Cable', 'Note']];
for (const l of topo.links) cab.push([l[0], l[1], l[2], l[3], cableName[l[4]], l[5] === 'optional' ? 'only for the rogue-device test' : l[5]]);
fs.writeFileSync(path.join(root, 'packet-tracer', 'cabling-plan.csv'), csv(cab));

console.log(`configs.js: ${Object.keys(configs).join(', ')}`);
console.log(`addressing-table.csv: ${addr.length - 1} rows, cabling-plan.csv: ${cab.length - 1} rows`);
